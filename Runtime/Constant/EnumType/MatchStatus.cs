namespace XmobiTea.GearN.Constant
{
    /// <summary>
    /// Enumerates the lifecycle state of a matchmaking ticket.
    /// </summary>
    public enum MatchStatus
    {
        /// <summary>
        /// Represents waiting for server.
        /// </summary>
        WaitingForServer = 1,
        /// <summary>
        /// Represents matched.
        /// </summary>
        Matched = 2,
        /// <summary>
        /// Represents canceled.
        /// </summary>
        Canceled = 3,

    }

}